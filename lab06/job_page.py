"""Scrape one job ad with BeautifulSoup (Lab 06, Part V).

Run it with:  python job_page.py
Install first: pip install requests beautifulsoup4

The script downloads a Google Careers job ad and prints its title, location
and description. The page also lists about 20 other jobs, so it first finds
the block with the job details and searches only inside it.

The class names (DkhPwc, r0wTof) are generated by Google's tools and can
change at any time. If the script stops working, open the page, find the
new names with the browser's developer tools (right click -> Inspect) and
update them here. The job ad itself may also be taken down.
"""

#https://www.google.com/about/careers/applications/jobs/results/78511373281043142-staff-machine-learning-engineer-youtube-live-discovery

import requests
from bs4 import BeautifulSoup

# The tracking parameters (?_gl=...) of the shared link are removed (Part III).
URL = ("https://www.google.com/about/careers/applications/jobs/results/"
       "78511373281043142-staff-machine-learning-engineer-youtube-live-discovery")
HEADERS = {"User-Agent": "IRCourseBot/0.1 (student lab crawler)"}

soup = BeautifulSoup(requests.get(URL, headers=HEADERS, timeout=10).text, "html.parser")

# The obvious searches find the wrong thing, because of the list of other jobs.
print("first <h2> on the page:", repr(soup.find("h2").get_text(strip=True)))
print("location spans on the page:", len(soup.select("span.r0wTof")))

# So first find the block with the job details, then search only inside it.
job = soup.select_one("div.DkhPwc")

title = job.find("h2").get_text(strip=True)
location = job.select_one("span.r0wTof").get_text(strip=True)

# The description: the paragraphs after the heading "About the job".
about = job.find("h3", string="About the job")
description = "\n".join(p.get_text(" ", strip=True) for p in about.find_next_siblings(["p", "div"]))

print()
print("title:      ", title)
print("location:   ", location)
print("description:", len(description.split()), "words")
print()
print(description)
